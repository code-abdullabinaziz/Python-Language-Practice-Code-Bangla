def check_voting_eligibility(age):
    if age < 18:
        return "ভোট দেওয়ার বয়স হয়নি!"  # শর্ত মিললে এখানেই ফাংশন শেষ
    
    return "আপনি ভোট দিতে পারবেন!"       # শর্ত না মিললে এই লাইন কাজ করবে

